"""Find the Unreal projects in the workspace and describe each, as JSON.

    selkies-modal-unreal-projects [FOLDER]

A developer clones their team's repository into the workspace with the GitHub
client, wherever they choose, so the session finds the `.uproject` files
rather than being told where they are: Moody's agent reads this
(`unreal_projects` in `addons/modal/sandbox.py`) to say which project it found
and what opening it will take. FOLDER is the workspace
(`SELKIES_MODAL_WORKSPACE`) unless given.

**Finding.** The folders are walked without following links, skipping hidden
ones (`.git`, and the workspace's `.home` and `.blender`) and the ones Unreal
and its tools regenerate (`Intermediate`, `Saved`, `DerivedDataCache`,
`Binaries`, and `node_modules`), at most eight deep. A folder holding a
`.uproject` is a project, and nothing under it is searched for another.

**Describing.** The output is a list, one object per project, sorted by path:

- `path`, `name` (the file's name without `.uproject`), and `folder`.
- `engine_association`: the engine the project was last saved with, as the file
  has it; `engine_version` is that when it is a version such as `5.4`, and null
  for a source build's identifier or none at all.
- `modules`: its C++ modules (`name`, `type`, `loading_phase`); a project with
  none is Blueprints only.
- `plugins`: the plugins it enables, each with `in_repository` (its
  `.uplugin` is in the project's `Plugins` folder), `source_in_repository` (that
  folder has its `Source`, so the engine's toolchain can build it), `path`, and
  `marketplace` (the `.uproject` names a Fab or Marketplace page for it). A
  plugin the `.uproject` enables is listed, and so is one in `Plugins` that it
  does not disable and whose descriptor does not leave off by default, as Unreal
  treats a project's own plugins. One that is in neither place comes from the
  engine, or from an install the engine machine does not have.
- `repository`: null outside Git, otherwise its `root`, `branch`, `remote`
  (without any credentials in it), its `submodules` and whether each is checked
  out, and `lfs`: whether files under the project are Git LFS files
  (`uses_lfs`, from the repository's attributes), how many (`files`), and how
  many hold their content rather than LFS's pointer (`fetched`, and
  `not_fetched`, which a clone without LFS, or with its download skipped, leaves).
- `size_bytes` and `size`: the project's files, without the folders skipped
  above, so the content actually checked out.

A `.uproject` that is not readable JSON is still listed, with `error` saying
why and its fields empty. Git is asked with `safe.directory` open, so the
description reads the same whichever user runs it; nothing here writes.

This is Python because the base image has it, and the descriptors are JSON.
"""

from __future__ import annotations

import json
import os
import re
import subprocess
import sys
from pathlib import Path
from typing import Any
from urllib.parse import urlsplit, urlunsplit

SKIPPED = frozenset({"Intermediate", "Saved", "DerivedDataCache", "Binaries", "node_modules"})
MAX_DEPTH = 8
LFS_POINTER = b"version https://git-lfs.github.com/spec/"
VERSION = re.compile(r"\d+\.\d+(\.\d+)?")


def skipped(name: str) -> bool:
    """Whether a folder of that name is left out of every walk: hidden, or regenerated by Unreal."""
    return name.startswith(".") or name in SKIPPED


def find_projects(root: Path) -> list[Path]:
    """Every `.uproject` under `root`, none searched for under a folder that already holds one."""
    found: list[Path] = []
    pending = [(root, 0)]
    while pending:
        folder, depth = pending.pop()
        try:
            entries = list(os.scandir(folder))
        except OSError:
            continue
        projects = [Path(e.path) for e in entries if e.name.endswith(".uproject") and e.is_file(follow_symlinks=False)]
        if projects:
            found.extend(projects)
            continue
        if depth < MAX_DEPTH:
            pending.extend(
                (Path(e.path), depth + 1) for e in entries if e.is_dir(follow_symlinks=False) and not skipped(e.name)
            )
    return sorted(found)


def read_json(path: Path) -> dict[str, Any]:
    """A descriptor's JSON object, which Unreal may write with a byte order mark.

    Raises:
        ValueError: The file is not a JSON object.
        OSError: The file cannot be read.
    """
    value = json.loads(path.read_text(encoding="utf-8-sig"))
    if not isinstance(value, dict):
        raise ValueError("not a JSON object")
    return value


def walk_files(folder: Path):
    """Every file under `folder`, with its `os.DirEntry`, skipping the folders `skipped` names and links."""
    pending = [folder]
    while pending:
        current = pending.pop()
        try:
            entries = list(os.scandir(current))
        except OSError:
            continue
        for entry in entries:
            if entry.is_dir(follow_symlinks=False):
                if not skipped(entry.name):
                    pending.append(Path(entry.path))
            elif entry.is_file(follow_symlinks=False):
                yield entry


def project_plugins(folder: Path) -> dict[str, dict[str, Any]]:
    """The plugins in the project's own `Plugins` folder, by name, with where each is and what it holds."""
    plugins: dict[str, dict[str, Any]] = {}
    for entry in walk_files(folder / "Plugins"):
        if not entry.name.endswith(".uplugin"):
            continue
        path = Path(entry.path)
        try:
            descriptor = read_json(path)
        except (OSError, ValueError):
            descriptor = {}
        plugins[path.stem] = {
            "path": str(path.relative_to(folder)),
            "has_source": (path.parent / "Source").is_dir(),
            # A project's own plugin is on unless its descriptor says otherwise
            "enabled_by_default": descriptor.get("EnabledByDefault", True) is not False,
        }
    return plugins


def enabled_plugins(descriptor: dict[str, Any], folder: Path) -> list[dict[str, Any]]:
    """The plugins the project runs with, and where each comes from."""
    declared = {
        entry["Name"]: entry
        for entry in descriptor.get("Plugins") or []
        if isinstance(entry, dict) and isinstance(entry.get("Name"), str)
    }
    local = project_plugins(folder)
    names = [name for name, entry in declared.items() if entry.get("Enabled", True) is not False]
    names += [name for name, plugin in local.items() if name not in declared and plugin["enabled_by_default"]]
    result = []
    for name in sorted(names, key=str.lower):
        plugin = local.get(name)
        result.append(
            {
                "name": name,
                "in_repository": plugin is not None,
                "source_in_repository": bool(plugin and plugin["has_source"]),
                "path": plugin["path"] if plugin else None,
                "marketplace": bool(declared.get(name, {}).get("MarketplaceURL")),
            }
        )
    return result


def modules(descriptor: dict[str, Any]) -> list[dict[str, Any]]:
    """The project's C++ modules, as its descriptor lists them."""
    return [
        {"name": entry.get("Name"), "type": entry.get("Type"), "loading_phase": entry.get("LoadingPhase")}
        for entry in descriptor.get("Modules") or []
        if isinstance(entry, dict)
    ]


def git(root: Path, *arguments: str, data: bytes | None = None) -> bytes | None:
    """What a read-only Git command printed in `root`, or None where it failed or Git is missing."""
    try:
        done = subprocess.run(
            ["git", "-c", "safe.directory=*", "-C", str(root), *arguments],
            input=data,
            capture_output=True,
            check=False,
            timeout=120,
        )
    except (OSError, subprocess.TimeoutExpired):
        return None
    return done.stdout if done.returncode == 0 else None


def without_credentials(url: str) -> str:
    """A remote's URL with any user name or token taken out of it."""
    parts = urlsplit(url)
    if not parts.netloc or "@" not in parts.netloc:
        return url
    host = parts.netloc.rsplit("@", 1)[1]
    return urlunsplit((parts.scheme, host, parts.path, parts.query, parts.fragment))


def lfs_state(root: Path, folder: Path) -> dict[str, Any]:
    """Which files under `folder` Git LFS keeps, and how many of them hold their content rather than a pointer.

    The files are the ones Git tracks there whose `filter` attribute is `lfs`;
    one still holding LFS's pointer text was never fetched. Git is asked from
    `folder`, which names its files relative to it.
    """
    listed = git(folder, "ls-files", "-z") or b""
    attributes = git(folder, "check-attr", "-z", "--stdin", "filter", data=listed) if listed else b""
    fields = (attributes or b"").split(b"\0")
    lfs_files = [fields[i] for i in range(0, len(fields) - 2, 3) if fields[i + 2] == b"lfs"]
    fetched = 0
    for name in lfs_files:
        try:
            with open(folder / os.fsdecode(name), "rb") as file:
                fetched += not file.read(len(LFS_POINTER)).startswith(LFS_POINTER)
        except OSError:
            pass
    attributes_text = ""
    for candidate in {root / ".gitattributes", folder / ".gitattributes"}:
        try:
            attributes_text += candidate.read_text(errors="replace")
        except OSError:
            pass
    return {
        "uses_lfs": bool(lfs_files) or "filter=lfs" in attributes_text,
        "files": len(lfs_files),
        "fetched": fetched,
        "not_fetched": len(lfs_files) - fetched,
    }


def submodules(root: Path) -> list[dict[str, Any]]:
    """The repository's submodules, and whether each is checked out."""
    listed = git(root, "config", "-f", ".gitmodules", "--get-regexp", r"^submodule\..*\.path$") or b""
    result = []
    for line in listed.decode(errors="replace").splitlines():
        path = line.split(" ", 1)[1] if " " in line else ""
        if path:
            checked_out = (root / path).is_dir() and any((root / path).iterdir())
            result.append({"path": path, "checked_out": checked_out})
    return result


def repository(folder: Path) -> dict[str, Any] | None:
    """The Git repository the project is in, or None outside one.

    Its root is found as the way up from the project folder (`--show-cdup`),
    so it is named by the same path the project is: Git's own name for it is
    the real path, which in a session is the Volume's mount point rather than
    the workspace's.
    """
    up = git(folder, "rev-parse", "--show-cdup")
    if up is None:
        return None
    root = Path(os.path.normpath(folder / up.decode().strip())) if up.strip() else folder
    branch = git(root, "rev-parse", "--abbrev-ref", "HEAD")
    remote = git(root, "remote", "get-url", "origin")
    return {
        "root": str(root),
        "branch": branch.decode().strip() if branch else None,
        "remote": without_credentials(remote.decode().strip()) if remote else None,
        "submodules": submodules(root),
        "lfs": lfs_state(root, folder),
    }


def size_text(size: int) -> str:
    """A size in bytes as people read it, in decimal units."""
    if size < 1000:
        return f"{size} bytes"
    value = size / 1000
    for unit in ("kB", "MB", "GB"):
        if value < 1000:
            return f"{value:.1f} {unit}"
        value /= 1000
    return f"{value:.1f} TB"


def describe(path: Path) -> dict[str, Any]:
    """Everything this reports about one `.uproject`."""
    folder = path.parent
    project: dict[str, Any] = {"path": str(path), "name": path.stem, "folder": str(folder)}
    try:
        descriptor = read_json(path)
    except (OSError, ValueError) as error:
        descriptor = {}
        project["error"] = f"{path.name} is not readable as a project descriptor: {error}"
    association = descriptor.get("EngineAssociation")
    association = association if isinstance(association, str) else ""
    size = sum(entry.stat(follow_symlinks=False).st_size for entry in walk_files(folder))
    project.update(
        {
            "engine_association": association,
            "engine_version": association if VERSION.fullmatch(association) else None,
            "modules": modules(descriptor),
            "plugins": enabled_plugins(descriptor, folder),
            "repository": repository(folder),
            "size_bytes": size,
            "size": size_text(size),
        }
    )
    return project


def main() -> int:
    """Print the description of every project under the folder given, or the workspace."""
    if len(sys.argv) > 2 or sys.argv[1:2] in (["-h"], ["--help"]):
        print("usage: selkies-modal-unreal-projects [FOLDER]", file=sys.stderr)
        return 2
    root = Path(sys.argv[1] if len(sys.argv) == 2 else os.environ.get("SELKIES_MODAL_WORKSPACE") or Path.cwd())
    if not root.is_dir():
        print(f"selkies-modal-unreal-projects: {root} is not a folder", file=sys.stderr)
        return 2
    json.dump([describe(path) for path in find_projects(root)], sys.stdout, indent=2)
    sys.stdout.write("\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
